# Обёртка Kairema для команды из терминала. Аргументы: папка по умолчанию, файл команды, файл с текущей папкой, файл с функциями.
# Нужна, чтобы «cd» помнился между командами и чтобы любой синтаксис команды работал (команда лежит в файле).
d="$1"; s="$2"; c="$3"; r="$4"
cd "$(cat "$c" 2>/dev/null)" 2>/dev/null || cd "$d"
. "$r" 2>/dev/null
. "$s"
k=$?
pwd > "$c" 2>/dev/null
exit $k
